// Inlines the @modelcontextprotocol/ext-apps browser bundle into a TS module so the
// MCP App HTML resource (served by our MCP server) is fully self-contained.
// The bundle ends with `export{a as B,...}`; we rewrite that into a global so it can
// run as a classic inline <script> inside the sandboxed iframe.
import fs from "node:fs";
import path from "node:path";

const pkgDir = path.join(process.cwd(), "node_modules", "@modelcontextprotocol", "ext-apps");
const src = fs.readFileSync(path.join(pkgDir, "dist/src/app-with-deps.js"), "utf8");

const m = src.match(/export\s*\{([^}]*)\};?\s*$/);
if (!m) throw new Error("ext-apps bundle: trailing export block not found");
const pairs = m[1]
  .split(",")
  .map((s) => s.trim())
  .filter(Boolean)
  .map((s) => {
    const [local, exported] = s.split(/\s+as\s+/);
    return `${JSON.stringify(exported ?? local)}:${local}`;
  });
const body = src.slice(0, m.index) + `\nglobalThis.ExtApps={${pairs.join(",")}};\n`;

const outDir = path.join(process.cwd(), "lib", "generated");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, "ext-apps-bundle.ts"),
  `// Generated by scripts/vendor-ext-apps.mjs. Do not edit.\nexport const EXT_APPS_BUNDLE: string = ${JSON.stringify(body)};\n`,
);
console.log(`ext-apps bundle inlined (${(body.length / 1024).toFixed(0)} KB, ${pairs.length} exports)`);
